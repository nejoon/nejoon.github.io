const supported = ['ko', 'en', 'ja'];
const storageKey = 'nejoon-basement-lang';
const listeners = new Set();
function initialLanguage() {
  const query = new URLSearchParams(window.location.search).get('lang');
  if (supported.includes(query)) {
    try { localStorage.setItem(storageKey, query); } catch { /* Session preference still works. */ }
    return query;
  }
  try { const saved = localStorage.getItem(storageKey); if (supported.includes(saved)) return saved; } catch { /* Storage may be disabled. */ }
  const browser = (navigator.language || '').toLowerCase();
  return browser.startsWith('ko') ? 'ko' : browser.startsWith('ja') ? 'ja' : 'en';
}
let language = initialLanguage();
