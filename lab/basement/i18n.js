export function t(key, values = {}) {
  const value = dictionary[language][key] ?? dictionary.ko[key] ?? key;
  return typeof value === 'string' ? value.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match) : value;
}
export function onLangChange(callback) { listeners.add(callback); return () => listeners.delete(callback); }
export function translateDOM(root = document) {
  for (const [attribute, target] of [['data-i18n', null], ['data-i18n-aria-label', 'aria-label'], ['data-i18n-content', 'content']]) {
    for (const node of root.querySelectorAll(`[${attribute}]`)) {
      const value = t(node.getAttribute(attribute));
      if (target) node.setAttribute(target, value); else node.textContent = value;
    }
  }
  for (const node of root.querySelectorAll('[data-lang]')) node.setAttribute('aria-pressed', String(node.dataset.lang === language));
}
export function setLang(value) {
  if (!supported.includes(value)) return;
  language = value;
  try { localStorage.setItem(storageKey, value); } catch { /* Session preference still works. */ }
  // Keep a supplied URL override consistent with subsequent manual choices.
  try { const url = new URL(window.location.href); if (url.searchParams.has('lang')) { url.searchParams.set('lang', value); history.replaceState(history.state, '', url); } } catch { /* Embedded/file pages may disallow history changes. */ }
  document.documentElement.lang = language;
  translateDOM();
  for (const callback of listeners) callback(language);
}
export function languageSwitch(terminal = false) {
  const group = document.createElement('div'); group.className = 'language-switch';
  group.setAttribute('role', 'group'); group.dataset.i18nAriaLabel = 'language';
  supported.forEach((lang, i) => {
    if (i && !terminal) { const separator = document.createElement('span'); separator.textContent = ' / '; separator.setAttribute('aria-hidden', 'true'); group.append(separator); }
    const button = document.createElement('button'); button.type = 'button'; button.dataset.lang = lang;
    button.textContent = terminal ? `/${lang}` : lang.toUpperCase(); button.lang = lang;
    button.addEventListener('click', () => setLang(lang)); group.append(button);
  });
  translateDOM(group); group.setAttribute('aria-label', t('language'));
  return group;
}
